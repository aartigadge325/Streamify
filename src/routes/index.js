const express = require('express');
const mongoose = require('mongoose');
const authRoutes = require('./auth.routes');
const videoRoutes = require('./video.routes');
const commentRoutes = require('./comment.routes');
const reactionRoutes = require('./reaction.routes');
const subscriptionRoutes = require('./subscription.routes');
const playlistRoutes = require('./playlist.routes');
const historyRoutes = require('./history.routes');
const profileRoutes = require('./profile.routes');
const adminRoutes = require('./admin.routes');
const openApiSpec = require('../../docs/openapi.json');
const router = express.Router();
router.get('/openapi.json', (_req, res) => res.json(openApiSpec));
router.get('/health/live', (_req, res) => res.status(200).json({ status: 'ok', service: 'streamify-api' }));
router.get('/health/ready', (_req, res) => { const databaseReady = mongoose.connection.readyState === 1; res.status(databaseReady ? 200 : 503).json({ status: databaseReady ? 'ready' : 'not-ready', service: 'streamify-api', dependencies: { database: databaseReady ? 'connected' : 'disconnected' } }); });
router.get('/health', (_req, res) => { const databaseReady = mongoose.connection.readyState === 1; res.status(databaseReady ? 200 : 503).json({ status: databaseReady ? 'ok' : 'not-ready', service: 'streamify-api' }); });
router.use('/auth', authRoutes);
router.use('/videos', videoRoutes);
router.use('/', commentRoutes);
router.use('/', reactionRoutes);
router.use('/subscriptions', subscriptionRoutes);
router.use('/playlists', playlistRoutes);
router.use('/history', historyRoutes);
router.use('/users', profileRoutes);
router.use('/admin', adminRoutes);
module.exports = router;
